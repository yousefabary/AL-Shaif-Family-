def build():
    # Chain: adam..jusham -> bakil..mufleh -> shaif founder -> حمد -> عايض(with all descendants)
    root = N(adam_chain[0])
    cur = root
    for nm in adam_chain[1:]:
        child = N(nm)
        cur["children"].append(child)
        cur = child
    # hashid side note attaches near Jusham (not expanded)
    cur["children"].append(hashid_note)
    for nm in bakil_to_shaif:
        child = N(nm)
        cur["children"].append(child)
        cur = child
    # shaif founder node, tagged specially
    shaif_node = N("محمد", note="محمد الشايف - الجد المؤسس الذي تنسب إليه الأسرة")
    cur["children"].append(shaif_node)
    cur = shaif_node
    hamad_node = N("حمد")
    cur["children"].append(hamad_node)
    aayidh_node = N("عايض", note="الجد عايض بن حمد")
    hamad_node["children"].append(aayidh_node)
    for c in aayidh[1]:
        aayidh_node["children"].append(norm(c))
    return root

if __name__ == "__main__":
    data = build()
    # flatten to list with ids + parentId
    out = []
    counter = [0]
    def walk(node, parent_id):
        counter[0] += 1
        nid = f"p{counter[0]}"
        out.append({
            "id": nid,
            "name": node["name"],
            "parentId": parent_id,
            "note": node.get("note"),
        })
        for c in node["children"]:
            walk(c, nid)
    walk(data, None)

    out_path = "api/_lib/seed.json" if os.path.isdir("api/_lib") else "seed.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print(f"total people: {len(out)} -> wrote {out_path}")
    print("Note: the API only auto-seeds an EMPTY database. If the database already")
    print("has people in it, truncate the `people` table (or use a fresh database)")
    print("after regenerating this file for the new seed data to apply.")
