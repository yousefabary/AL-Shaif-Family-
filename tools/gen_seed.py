"""
Builds seed.json for the Al-Shaif family tree app from data transcribed
by hand (via careful visual reading) from the source poster
"مشجر آل الشايف - النسخة الثانية" (Al-Shaif family tree, 2nd edition, 2018,
compiled by eng. Najm Aldeen Nasser Hassan Al-Shaif, based on the first
edition by Capt. Ali bin Naji bin Ahmed Al-Shaif, 1403H).

Given the extreme density of the original poster (many hundreds of names
in small clusters connected by curved lines, some crossing), this is a
best-effort transcription. The ancestral backbone (Adam -> Al-Shaif line)
and all major named branches are transcribed with high confidence. Leaf-level
descendant clusters are grouped under their nearest correctly-identified
local parent as read directly off the source tiles.

Data shape: nested tuples (name, [children...]) where a child is either
   - a plain string (leaf, no known children), or
   - another (name, [children]) tuple
Optional per-node metadata (e.g. notes) can be added via a dict child:
   {"name": "...", "note": "...", "children": [...]}
"""
import json, os, sys

def N(name, children=None, note=None):
    return {"name": name, "children": children or [], "note": note}

def norm(x):
    """normalize a raw child entry (str | tuple | dict) into a node dict"""
    if isinstance(x, str):
        return N(x)
    if isinstance(x, dict):
        return x
    if isinstance(x, tuple):
        name, children = x
        return N(name, [norm(c) for c in children])
    raise ValueError(x)

